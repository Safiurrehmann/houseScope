        CREATE TABLE IF NOT EXISTS stages(id BIGSERIAL PRIMARY KEY,run TEXT,name TEXT,state TEXT,detail TEXT,started DOUBLE PRECISION,ended DOUBLE PRECISION);
        CREATE TABLE IF NOT EXISTS budget_versions(id BIGSERIAL PRIMARY KEY,report TEXT,revision INTEGER,payload TEXT,snapshot TEXT,catalog_version TEXT,created DOUBLE PRECISION,UNIQUE(report,revision));
